#!/usr/bin/env node
// SPDX-License-Identifier: Apache-2.0
// `pnpm brand --name "Acme" --color "#2563eb" [--logo path/to/mark.svg]`
//
// Rebrands the kit in one step: product name, accent colour, favicon and app icons.
// Run with no arguments to regenerate the default Rose assets.
import { spawnSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { faviconSvg, hexToRgb, markPng, markSvg, wordmarkSvg } from "./icons.mjs";
import { ADMIN_DIR, APP_DIR, ROOT, fail, ok, parseArgs, readText, setVar, warn, writeText } from "./lib.mjs";

const args = parseArgs();
if (args.help) {
  console.log('Usage: pnpm brand --name "Acme" --color "#2563eb" [--logo mark.svg]');
  process.exit(0);
}

const currentName = /"APP_NAME"\s*:\s*"([^"]*)"/.exec(readText(join(APP_DIR, "wrangler.jsonc")))?.[1] ?? "Rose";
const name = typeof args.name === "string" ? args.name.trim() : currentName;
if (!name || name.length > 40 || /[<>"&\\]/.test(name)) fail('--name must be 1–40 characters without < > " & \\');
const color = (typeof args.color === "string" ? args.color : readBrandColor() ?? "#e11d48").toLowerCase();
if (!/^#([0-9a-f]{3}|[0-9a-f]{6})$/.test(color)) fail("--color must be a hex colour such as #2563eb");

// ── Colour maths (WCAG relative luminance) ─────────────────────────────────────────
const toHex = (rgb) => `#${rgb.map((v) => Math.round(Math.min(255, Math.max(0, v))).toString(16).padStart(2, "0")).join("")}`;
const mix = (a, b, t) => toHex(hexToRgb(a).map((v, i) => v + (hexToRgb(b)[i] - v) * t));
const lum = (hex) => {
  const [r, g, b] = hexToRgb(hex).map((v) => (v / 255 <= 0.03928 ? v / 255 / 12.92 : ((v / 255 + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const contrast = (a, b) => (Math.max(lum(a), lum(b)) + 0.05) / (Math.min(lum(a), lum(b)) + 0.05);
const on = (bg) => (contrast(bg, "#ffffff") >= 4.5 ? "#ffffff" : "#0b0b0f");

const accent = color.length === 4 ? toHex(hexToRgb(color)) : color;
// Dark theme: lighten until the accent reads clearly on a near-black surface.
// The default Rose pair is hand-picked; any other colour gets a computed dark variant.
let accentDark = accent === "#e11d48" ? "#fb7185" : accent;
for (let t = 0; contrast(accentDark, "#0f0f12") < 6 && t <= 1; t += 0.05) accentDark = mix(accent, "#ffffff", t);
const accentContrast = on(accent);
const accentDarkContrast = on(accentDark);
if (contrast(accent, "#ffffff") < 3) warn(`${accent} is very light: buttons will use dark text and the accent may be hard to see on white surfaces.`);

function readBrandColor() {
  const p = join(ROOT, "packages/ui/src/brand.css");
  if (!existsSync(p)) return null;
  return /brand:start[\s\S]*?--accent:\s*(#[0-9a-fA-F]{3,6})/.exec(readText(p))?.[1] ?? null;
}

// ── 1. UI tokens ───────────────────────────────────────────────────────────────────
const brandCss = join(ROOT, "packages/ui/src/brand.css");
const block = `/* brand:start */
/* Generated by \`pnpm brand\`. Edit with that command, not by hand. */
:root {
  --accent: ${accent};
  --accent-contrast: ${accentContrast};
}
:root[data-theme="dark"] {
  --accent: ${accentDark};
  --accent-contrast: ${accentDarkContrast};
}
/* brand:end */`;
if (existsSync(brandCss)) {
  const css = readText(brandCss);
  writeText(brandCss, /\/\* brand:start \*\/[\s\S]*?\/\* brand:end \*\//.test(css) ? css.replace(/\/\* brand:start \*\/[\s\S]*?\/\* brand:end \*\//, block) : `${css.replace(/\s*$/, "")}\n\n${block}\n`);
} else {
  mkdirSync(join(ROOT, "packages/ui/src"), { recursive: true });
  writeText(brandCss, `/* SPDX-License-Identifier: Apache-2.0 */\n${block}\n`);
}
ok(`Accent ${accent} (dark theme ${accentDark}) → packages/ui/src/brand.css`);

// ── 2. Name ────────────────────────────────────────────────────────────────────────
for (const dir of [APP_DIR, ADMIN_DIR]) {
  const cfg = join(dir, "wrangler.jsonc");
  writeText(cfg, setVar(readText(cfg), "APP_NAME", name));
  const dev = join(dir, ".dev.vars");
  if (existsSync(dev)) {
    const lines = readFileSync(dev, "utf8").split("\n").filter((l) => l && !l.startsWith("APP_NAME="));
    writeFileSync(dev, [...lines, `APP_NAME=${name}`].join("\n") + "\n", { mode: 0o600 });
  }
  const html = join(dir, "index.html");
  if (existsSync(html)) {
    const title = dir === ADMIN_DIR ? `${name} Admin` : name;
    writeText(html, readText(html).replace(/<title>[^<]*<\/title>/, `<title>${title.replace(/&/g, "&amp;")}</title>`));
  }
}
ok(`Product name "${name}" → wrangler vars, .dev.vars, page titles`);

// ── 3. Icons ───────────────────────────────────────────────────────────────────────
const logo = typeof args.logo === "string" ? args.logo : null;
if (logo && (!existsSync(logo) || !/\.svg$/i.test(logo))) fail(`--logo must be an existing .svg file: ${logo}`);
if (logo && /<script|\son\w+\s*=|javascript:/i.test(readText(logo))) fail("--logo contains script content. Use a plain SVG.");

/** Rasterise an arbitrary SVG with whatever the machine has. Returns false if nothing works. */
function rasterise(svgPath, px, outPath) {
  const tries = [
    ["rsvg-convert", ["-w", String(px), "-h", String(px), "-o", outPath, svgPath]],
    ["magick", ["-background", "none", "-density", "384", svgPath, "-resize", `${px}x${px}`, outPath]],
    ["inkscape", [svgPath, "-w", String(px), "-h", String(px), "-o", outPath]],
  ];
  for (const [cmd, a] of tries) {
    const r = spawnSync(cmd, a, { stdio: "ignore" });
    if (r.status === 0 && existsSync(outPath)) return true;
  }
  // macOS Quick Look as a last resort.
  const tmp = mkdtempSync(join(tmpdir(), "rose-brand-"));
  try {
    const r = spawnSync("qlmanage", ["-t", "-s", String(px), "-o", tmp, svgPath], { stdio: "ignore" });
    const produced = join(tmp, `${svgPath.split("/").pop()}.png`);
    if (r.status === 0 && existsSync(produced)) {
      renameSync(produced, outPath);
      return true;
    }
  } catch {
    /* not macOS */
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
  return false;
}

mkdirSync(join(ROOT, "brand"), { recursive: true });
const sizes = [["apple-touch-icon.png", 180, true], ["icon-192.png", 192, false], ["icon-512.png", 512, false]];
let rasterFailed = false;
if (!logo) {
  writeText(join(ROOT, "brand/logo-mark.svg"), markSvg({ bg: accent, fg: accentContrast, title: name }));
  writeText(join(ROOT, "brand/logo-wordmark.svg"), wordmarkSvg({ bg: accent, fg: accentContrast, text: "#18181b", name }));
  writeText(join(ROOT, "brand/logo-wordmark-dark.svg"), wordmarkSvg({ bg: accentDark, fg: accentDarkContrast, text: "#fafafa", name }));
}
for (const dir of [APP_DIR, ADMIN_DIR]) {
  const pub = join(dir, "public");
  mkdirSync(pub, { recursive: true });
  if (logo) {
    copyFileSync(logo, join(pub, "favicon.svg"));
    for (const [file, px] of sizes) if (!rasterise(logo, px, join(pub, file))) rasterFailed = true;
  } else {
    writeText(join(pub, "favicon.svg"), faviconSvg({ bg: accent, fg: accentContrast, bgDark: accentDark, fgDark: accentDarkContrast }));
    // Apple applies its own rounded mask, so that icon is full-bleed with a slightly smaller glyph.
    for (const [file, px, fullBleed] of sizes) writeFileSync(join(pub, file), markPng(px, { bg: accent, fg: accentContrast, fullBleed, glyphScale: fullBleed ? 0.82 : 1 }));
  }
  const appName = dir === ADMIN_DIR ? `${name} Admin` : name;
  writeText(
    join(pub, "site.webmanifest"),
    JSON.stringify(
      {
        name: appName, short_name: appName.slice(0, 12), start_url: "/", display: "standalone", background_color: "#ffffff", theme_color: accent,
        icons: [
          { src: "/icon-192.png", sizes: "192x192", type: "image/png" },
          { src: "/icon-512.png", sizes: "512x512", type: "image/png" },
          { src: "/favicon.svg", sizes: "any", type: "image/svg+xml" },
        ],
      },
      null,
      2,
    ) + "\n",
  );
}
if (logo) {
  copyFileSync(logo, join(ROOT, "brand/logo-mark.svg"));
  if (rasterFailed) warn("Could not convert your SVG to PNG on this machine (needs rsvg-convert, ImageMagick, Inkscape or macOS). favicon.svg is in place; export apple-touch-icon.png (180), icon-192.png and icon-512.png yourself into apps/*/public/.");
  warn("brand/logo-wordmark*.svg still show the default mark. Replace them with your own wordmark.");
}
ok(`Icons and web manifest → apps/app/public, apps/admin/public${logo ? "" : ", brand/"}`);
console.log("\nRestart `pnpm dev` to see the change. Commit the updated files.");
